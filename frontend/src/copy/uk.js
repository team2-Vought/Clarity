const plural = (n, one, few, many) => {
  const tens = n % 100;
  if (n % 10 === 1 && tens !== 11) return one;
  if (n % 10 >= 2 && n % 10 <= 4 && (tens < 12 || tens > 14)) return few;
  return many;
};

